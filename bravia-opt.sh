# 7. Restore / Rollback Packages
cmd_restore() {
    ensure_adb
    local target="${1:-latest}"

    # If user passed a single package name (contains a dot and isn't a directory)
    if [[ "${target}" == *.* && ! -d "${target}" && ! -d "${BACKUP_ROOT}/${target}" ]]; then
        log_step "Restoring Single Package: ${target}"
        adb_tv shell cmd package install-existing --user 0 "${target}" || true
        adb_tv shell pm enable --user 0 "${target}" || true
        log_ok "Restored package: ${target}"
        return 0
    fi

    local bdir="${target}"
    if [[ ! -d "${bdir}" ]]; then
        bdir="${BACKUP_ROOT}/${target}"
    fi
    if [[ ! -f "${bdir}/removed_packages.log" ]]; then
        log_error "No removed_packages.log found in ${bdir}."
        log_info "You can also restore any specific package via: ./bravia-opt.sh restore <package.name>"
        return 1
    fi

    log_step "Restoring All Packages from ${bdir}/removed_packages.log"
    local pkg
    while IFS= read -r pkg; do
        [[ -z "${pkg}" ]] && continue
        adb_tv shell cmd package install-existing --user 0 "${pkg}" >/dev/null 2>&1 || true
        adb_tv shell pm enable --user 0 "${pkg}" >/dev/null 2>&1 || true
        log_ok "Restored: ${pkg}"
    done < <(sort -u "${bdir}/removed_packages.log")

    log_info "Restoring default 1.0x animation scales & 400ms long-press timeout..."
    adb_tv shell settings put global window_animation_scale 1.0
    adb_tv shell settings put global transition_animation_scale 1.0
    adb_tv shell settings put global animator_duration_scale 1.0
    adb_tv shell settings put secure long_press_timeout 400
    log_ok "Full rollback complete!"
}

