#!/usr/bin/env bash
# ==============================================================================
# Sony Bravia (Android TV / Google TV) Network Debloat & Optimization CLI
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${SCRIPT_DIR}/.bravia.env"
CONF_FILE="${SCRIPT_DIR}/packages.conf"
BACKUP_ROOT="${SCRIPT_DIR}/backups"
CACHE_DIR="${SCRIPT_DIR}/.cache"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

log_info()  { echo -e "${BLUE}[INFO]${NC} $*"; }
log_ok()    { echo -e "${GREEN}[OK]${NC}   $*"; }
log_warn()  { echo -e "${YELLOW}[WARN]${NC} $*"; }
log_error() { echo -e "${RED}[ERR]${NC}  $*" >&2; }
log_step()  { echo -e "\n${BOLD}${CYAN}==> $*${NC}"; }

if [[ ! -f "${CONF_FILE}" ]]; then
    log_error "Missing configuration file: ${CONF_FILE}"
    exit 1
fi
# shellcheck source=packages.conf
source "${CONF_FILE}"

# Load local .bravia.env if present
if [[ -f "${ENV_FILE}" ]]; then
    # shellcheck disable=SC1090
    source "${ENV_FILE}"
fi

TV_NAME="${TV_NAME:-BRAVIA}"
TV_MDNS_HOST="${TV_MDNS_HOST:-Android.local.}"
TV_MAC="${TV_MAC:-}"
TV_FALLBACK_IP="${TV_FALLBACK_IP:-}"
ADB_PORT="${ADB_PORT:-5555}"
ANIMATION_SCALE="${ANIMATION_SCALE:-0.0}"
LONG_PRESS_TIMEOUT="${LONG_PRESS_TIMEOUT:-250}"
MAX_CACHED_PROCESSES="${MAX_CACHED_PROCESSES:-2}"

# Check if a package matches any entry/glob in PROTECTED_PACKAGES
is_protected() {
    local pkg="$1"
    local pattern
    for pattern in "${PROTECTED_PACKAGES[@]}"; do
        # Intentional glob matching on right-hand side
        # shellcheck disable=SC2053
        if [[ "${pkg}" == ${pattern} ]]; then
            return 0
        fi
    done
    return 1
}

# Expand an array of package names/globs against the TV's currently enabled packages
expand_target_packages() {
    local enabled_pkgs="$1"
    shift
    local patterns=("$@")
    local pat pkg
    for pat in "${patterns[@]}"; do
        while IFS= read -r pkg; do
            [[ -z "${pkg}" ]] && continue
            # shellcheck disable=SC2053
            if [[ "${pkg}" == ${pat} ]]; then
                echo "${pkg}"
            fi
        done <<< "${enabled_pkgs}"
    done
}

# Initialize .bravia.env by discovering Sony Bravia / Android TV on the LAN
cmd_init() {
    log_step "Initializing Local TV Target Configuration (.bravia.env)"
    local discovered_ip="${TV_IP:-}"
    local discovered_host="${TV_MDNS_HOST}"
    local discovered_name="${TV_NAME}"
    local discovered_mac=""

    if [[ -z "${discovered_ip}" ]] && command -v dns-sd >/dev/null 2>&1; then
        log_info "Scanning mDNS (_adb._tcp & _androidtvremote2._tcp) for Sony Bravia / Android TV..."
        local mdns_info
        mdns_info="$(python3 -c '
import subprocess, time, re

def run_dnssd(args, wait=1.5):
    p = subprocess.Popen(["dns-sd"] + args, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
    time.sleep(wait)
    p.terminate()
    out, _ = p.communicate()
    return out

name = ""
host = "Android.local."
b_out = run_dnssd(["-B", "_androidtvremote2._tcp", "local."])
for line in b_out.splitlines():
    if "_androidtvremote2._tcp." in line and "Add" in line:
        name = line.split("_androidtvremote2._tcp.")[-1].strip()
        break

if name:
    l_out = run_dnssd(["-L", name, "_androidtvremote2._tcp", "local."])
    m_host = re.search(r"can be reached at\s+([^\s:]+):", l_out)
    if m_host:
        host = m_host.group(1)

g_out = run_dnssd(["-G", "v4", host])
m_ip = re.search(re.escape(host) + r"\s+(\d+\.\d+\.\d+\.\d+)", g_out)
ip = m_ip.group(1) if m_ip else ""
print(f"{name}|{host}|{ip}")
' 2>/dev/null || true)"

        IFS='|' read -r m_name m_host m_ip <<< "${mdns_info}"
        [[ -n "${m_name:-}" ]] && discovered_name="${m_name}"
        [[ -n "${m_host:-}" ]] && discovered_host="${m_host}"
        [[ -n "${m_ip:-}" ]] && discovered_ip="${m_ip}"
    fi

    if [[ -z "${discovered_ip}" ]]; then
        read -r -p "Could not auto-resolve TV IP via mDNS. Enter your Sony Bravia IPv4 address: " discovered_ip
    fi

    # Ping once to populate ARP cache, then extract hardware MAC
    ping -c 1 -W 1000 "${discovered_ip}" >/dev/null 2>&1 || true
    discovered_mac="$(arp -a 2>/dev/null | grep "(${discovered_ip})" | grep -oE '([0-9a-fA-F]{1,2}:){5}[0-9a-fA-F]{1,2}' | head -n 1 || true)"

    cat > "${ENV_FILE}" <<EOF
# Local TV target configuration (generated by './bravia-opt.sh init')
TV_NAME="${discovered_name}"
TV_MDNS_HOST="${discovered_host}"
TV_MAC="${discovered_mac}"
TV_FALLBACK_IP="${discovered_ip}"
ADB_PORT="${ADB_PORT}"

# Tuning preferences
ANIMATION_SCALE="${ANIMATION_SCALE}"          # 0.0 = instant & static focus | 0.6 = fast w/ gentle focus pulse | 1.0 = stock
LONG_PRESS_TIMEOUT="${LONG_PRESS_TIMEOUT}"       # D-pad hold-to-scroll repeat delay in ms (stock = 400)
MAX_CACHED_PROCESSES="${MAX_CACHED_PROCESSES}"       # ActivityManager background cached process cap (stock = 16-32)
EOF

    # Reload newly written .bravia.env
    # shellcheck disable=SC1090
    source "${ENV_FILE}"
    log_ok "Wrote ${ENV_FILE}: Name='${TV_NAME}' | Host='${TV_MDNS_HOST}' | IP='${TV_FALLBACK_IP}' | MAC='${TV_MAC:-unknown}'"
}

# Resolve TV IP via: 1) TV_IP env override, 2) mDNS (TV_MDNS_HOST), 3) ARP MAC (TV_MAC), 4) TV_FALLBACK_IP
resolve_tv_ip() {
    if [[ -n "${TV_IP:-}" ]]; then
        echo "${TV_IP}"
        return 0
    fi

    if [[ ! -f "${ENV_FILE}" && -z "${TV_FALLBACK_IP}" ]]; then
        cmd_init >&2
    fi

    local resolved=""
    if command -v dns-sd >/dev/null 2>&1 && [[ -n "${TV_MDNS_HOST}" ]]; then
        resolved="$(python3 -c "
import subprocess, time, re
host = '${TV_MDNS_HOST}'
p = subprocess.Popen(['dns-sd', '-G', 'v4', host], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
time.sleep(1.5)
p.terminate()
out, _ = p.communicate()
m = re.search(re.escape(host) + r'\s+(\d+\.\d+\.\d+\.\d+)', out)
if m:
    print(m.group(1))
" 2>/dev/null || true)"
    fi

    if [[ -z "${resolved}" && -n "${TV_MAC}" ]]; then
        resolved="$(arp -a 2>/dev/null | grep -i "${TV_MAC}" | sed -E 's/.*\(([0-9.]+)\).*/\1/' | head -n 1 || true)"
    fi

    if [[ -n "${resolved}" ]]; then
        echo "${resolved}"
    else
        echo "${TV_FALLBACK_IP}"
    fi
}

# Ensure ADB is connected and authorized to the Bravia TV
ensure_adb() {
    local ip
    ip="$(resolve_tv_ip)"
    if [[ -z "${ip}" ]]; then
        log_error "No TV IP resolved. Run './bravia-opt.sh init' or set TV_IP=<ip>."
        return 1
    fi
    local target="${ip}:${ADB_PORT}"

    if adb devices | grep -qE "^${target}[[:space:]]+device$"; then
        export ADB_TARGET="${target}"
        return 0
    fi

    log_info "Connecting to ${TV_NAME} at ${target}..."
    local connect_out
    connect_out="$(adb connect "${target}" 2>&1 || true)"
    echo "       ${connect_out}"

    if [[ "${connect_out}" == *"No route to host"* ]] && command -v osascript >/dev/null 2>&1; then
        log_info "Bypassing macOS IDE Local Network filter by starting ADB daemon via Terminal.app..."
        adb kill-server >/dev/null 2>&1 || true
        osascript -e "tell application \"Terminal\" to do script \"$(command -v adb) start-server && $(command -v adb) connect ${target}\"" >/dev/null 2>&1 || true
        sleep 3
    fi

    sleep 1
    if adb devices | grep -qE "^${target}[[:space:]]+unauthorized$"; then
        log_warn "Connection pending authorization on TV screen!"
        log_warn "Look at your Sony Bravia TV, check 'Always allow from this computer', and press OK."
        log_info "Waiting up to 30 seconds for authorization..."
        for _ in {1..15}; do
            sleep 2
            if adb devices | grep -qE "^${target}[[:space:]]+device$"; then
                log_ok "Authorized and connected to ${target}!"
                export ADB_TARGET="${target}"
                return 0
            fi
        done
    fi

    if adb devices | grep -qE "^${target}[[:space:]]+device$"; then
        log_ok "Connected to ${target}!"
        export ADB_TARGET="${target}"
        return 0
    fi

    log_error "Could not connect to ${TV_NAME} at ${target}."
    printf "%b\n" "
${BOLD}Troubleshooting Checklist:${NC}
  1. Make sure the TV is turned ON (awake, not in standby).
  2. On the TV remote: Settings -> System (or Device Preferences) -> About
     Scroll to 'Android TV OS build' and press OK 7 times until Developer mode is enabled.
  3. Go back to Settings -> System -> Developer options -> Enable 'USB debugging' (and 'Network debugging' if shown).
  4. Re-run: ./bravia-opt.sh discover"
    return 1
}

adb_tv() {
    adb -s "${ADB_TARGET}" "$@" < /dev/null
}

# 1. Discover & Connect
cmd_discover() {
    log_step "Discovering ${TV_NAME} on Local Network"
    local ip
    ip="$(resolve_tv_ip)"
    log_info "Resolved ${TV_NAME} IP: ${BOLD}${ip}${NC} (${TV_MDNS_HOST})"
    ensure_adb
    local model build android_ver
    model="$(adb_tv shell getprop ro.product.model | tr -d '\r')"
    build="$(adb_tv shell getprop ro.build.display.id | tr -d '\r')"
    android_ver="$(adb_tv shell getprop ro.build.version.release | tr -d '\r')"
    log_ok "Device Verified: Model='${model}' | Android='${android_ver}' | Build='${build}'"
}

# 2. System Audit (RAM, Storage, Active Bloatware)
cmd_audit() {
    ensure_adb
    log_step "Sony Bravia System & Bloatware Audit"

    echo -e "${BOLD}--- Memory Usage (/proc/meminfo) ---${NC}"
    adb_tv shell "grep -E 'MemTotal|MemFree|MemAvailable|Cached|SwapTotal|SwapFree' /proc/meminfo" | sed 's/^/  /'

    echo -e "\n${BOLD}--- Internal Storage Usage (/data) ---${NC}"
    adb_tv shell "df -h /data" | sed 's/^/  /'

    echo -e "\n${BOLD}--- Current UI & Runtime Settings ---${NC}"
    local win_scale trans_scale anim_scale lp_timeout acc_en am_const
    win_scale="$(adb_tv shell settings get global window_animation_scale | tr -d '\r')"
    trans_scale="$(adb_tv shell settings get global transition_animation_scale | tr -d '\r')"
    anim_scale="$(adb_tv shell settings get global animator_duration_scale | tr -d '\r')"
    lp_timeout="$(adb_tv shell settings get secure long_press_timeout | tr -d '\r')"
    acc_en="$(adb_tv shell settings get secure accessibility_enabled | tr -d '\r')"
    am_const="$(adb_tv shell settings get global activity_manager_constants | tr -d '\r')"
    echo "  window_animation_scale     = ${win_scale}"
    echo "  transition_animation_scale = ${trans_scale}"
    echo "  animator_duration_scale    = ${anim_scale}"
    echo "  long_press_timeout         = ${lp_timeout} ms"
    echo "  accessibility_enabled      = ${acc_en}"
    echo "  activity_manager_constants = ${am_const}"

    echo -e "\n${BOLD}--- Active Bloatware Packages Currently Enabled on TV ---${NC}"
    local enabled_pkgs
    enabled_pkgs="$(adb_tv shell pm list packages -e | sed 's/^package://;s/\r$//')"

    local matched_pkgs
    matched_pkgs="$(expand_target_packages "${enabled_pkgs}" \
        "${SONY_BLOAT_PACKAGES[@]}" \
        "${TELEMETRY_AND_GOOGLE_BLOAT[@]}" \
        "${STOCK_LAUNCHER_PACKAGES[@]}" | sort -u)"

    local count=0
    local pkg
    while IFS= read -r pkg; do
        [[ -z "${pkg}" ]] && continue
        if ! is_protected "${pkg}"; then
            echo -e "  ${YELLOW}[ACTIVE]${NC} ${pkg}"
            ((count++)) || true
        fi
    done <<< "${matched_pkgs}"

    if [[ ${count} -eq 0 ]]; then
        log_ok "Zero targeted bloatware packages are currently active!"
    else
        log_warn "${count} targeted bloatware/launcher packages are currently enabled and consuming resources."
    fi
}

# 3. Backup Package & Settings State
cmd_backup() {
    ensure_adb
    local ts
    ts="$(date +%Y%m%d-%H%M%S)"
    local bdir="${BACKUP_ROOT}/${ts}"
    mkdir -p "${bdir}"

    log_step "Creating Pre-Flight Backup in ${bdir}"
    adb_tv shell pm list packages -u | sed 's/^package://;s/\r$//' | sort > "${bdir}/all_packages_uninstalled_incl.txt"
    adb_tv shell pm list packages -e | sed 's/^package://;s/\r$//' | sort > "${bdir}/enabled_packages.txt"
    adb_tv shell pm list packages -d | sed 's/^package://;s/\r$//' | sort > "${bdir}/disabled_packages.txt"
    adb_tv shell settings list global | tr -d '\r' > "${bdir}/settings_global.txt"
    ln -sfn "${bdir}" "${BACKUP_ROOT}/latest"

    log_ok "Saved package and settings snapshot to ${bdir}"
}

# 4. Sideload & Activate Projectivy Launcher (+ SmartTube) Safely
cmd_install_launcher() {
    ensure_adb
    log_step "Installing & Activating Projectivy Launcher (com.spocky.projengmenu) & SmartTube"
    mkdir -p "${CACHE_DIR}"

    local apk_file
    apk_file="$(find "${CACHE_DIR}" -maxdepth 1 -name 'ProjectivyLauncher-*.apk' | sort -V | tail -n 1 || true)"
    if [[ -z "${apk_file}" || ! -f "${apk_file}" ]]; then
        log_info "Querying GitHub API (spocky/miproja1) for latest Projectivy Launcher APK..."
        local apk_url
        apk_url="$(curl -sL https://api.github.com/repos/spocky/miproja1/releases/latest | python3 -c '
import sys, json
data = json.load(sys.stdin)
for asset in data.get("assets", []):
    url = asset.get("browser_download_url", "")
    if url.endswith(".apk"):
        print(url)
        break
')"
        if [[ -z "${apk_url}" ]]; then
            log_error "Failed to fetch Projectivy Launcher APK URL from GitHub."
            return 1
        fi
        apk_file="${CACHE_DIR}/$(basename "${apk_url}")"
        log_info "Downloading $(basename "${apk_url}")..."
        curl -L --fail --progress-bar -o "${apk_file}" "${apk_url}"
    else
        log_info "Using cached Projectivy APK: ${apk_file}"
    fi

    log_info "Sideloading Projectivy Launcher onto ${TV_NAME}..."
    adb_tv install -r "${apk_file}"

    # Verify installation before configuring launcher
    if ! adb_tv shell pm list packages -e | tr -d '\r' | grep -qx "package:com.spocky.projengmenu"; then
        log_error "Projectivy Launcher installation could not be verified! Aborting launcher switch."
        return 1
    fi
    log_ok "Projectivy Launcher (com.spocky.projengmenu) verified installed!"

    # Also install SmartTube (Ad-Free YouTube) & TV Bro (Web Browser) if cached
    local st_apk
    st_apk="$(find "${CACHE_DIR}" -maxdepth 1 -name 'SmartTube*armeabi-v7a.apk' | sort -V | tail -n 1 || true)"
    if [[ -n "${st_apk}" && -f "${st_apk}" ]]; then
        log_info "Sideloading cached SmartTube APK ($(basename "${st_apk}"))..."
        adb_tv install -r "${st_apk}" || true
    fi

    local tvbro_apk
    tvbro_apk="$(find "${CACHE_DIR}" -maxdepth 1 -name 'tvbro-*.apk' | sort -V | tail -n 1 || true)"
    if [[ -n "${tvbro_apk}" && -f "${tvbro_apk}" ]]; then
        log_info "Sideloading cached TV Bro Browser APK ($(basename "${tvbro_apk}"))..."
        adb_tv install -r "${tvbro_apk}" || true
    fi

    log_info "Configuring Projectivy Launcher as default Home & enabling its Accessibility Home-hook..."
    adb_tv shell cmd package set-home-activity "com.spocky.projengmenu/com.spocky.projengmenu.ui.home.MainActivity" || true
    adb_tv shell settings put secure enabled_accessibility_services "com.spocky.projengmenu/com.spocky.projengmenu.services.ProjectivyAccessibilityService" || true
    adb_tv shell settings put secure accessibility_enabled 1 || true

    # IMPORTANT COLD-BOOT SAFEGUARD:
    # Keep com.google.android.tvlauncher installed as the system-signed Android 11 Direct Boot
    # HOME fallback so the TV never hangs on bootanimation, while throttling its background CPU/RAM
    # and disabling the heavy Google TV ad/recommendation banner service (tvrecommendations).
    adb_tv shell cmd appops set com.google.android.tvlauncher RUN_IN_BACKGROUND ignore >/dev/null 2>&1 || true
    adb_tv shell cmd appops set com.google.android.tvlauncher RUN_ANY_IN_BACKGROUND ignore >/dev/null 2>&1 || true

    log_info "Disabling stock Google/Sony ad & recommendation engines (keeping tvlauncher as DirectBoot fallback)..."
    local enabled_pkgs pkg
    enabled_pkgs="$(adb_tv shell pm list packages -e | sed 's/^package://;s/\r$//')"
    while IFS= read -r pkg; do
        [[ -z "${pkg}" ]] && continue
        disable_or_uninstall_pkg "${pkg}" "false"
    done < <(expand_target_packages "${enabled_pkgs}" "${STOCK_LAUNCHER_PACKAGES[@]}" | sort -u)

    # Launch Projectivy immediately so the user sees the new home screen
    adb_tv shell monkey -p com.spocky.projengmenu -c android.intent.category.HOME 1 >/dev/null 2>&1 || true
    log_ok "Projectivy Launcher is active and cold-boot DirectBoot fallback is preserved!"
}

# Helper to disable/uninstall a single package for user 0 safely (with Cold-Boot Safeguards)
disable_or_uninstall_pkg() {
    local pkg="$1"
    local dry_run="${2:-false}"

    if is_protected "${pkg}"; then
        log_warn "Skipping protected package: ${pkg}"
        return 0
    fi

    local enabled_list
    enabled_list="$(adb_tv shell pm list packages -e | sed 's/^package://;s/\r$//')"
    if ! echo "${enabled_list}" | grep -qx "${pkg}"; then
        return 0
    fi

    # Inspect package metadata to enforce Cold-Boot Safeguards:
    # 1. Never disable/uninstall shared UID 1000 (android.uid.system) packages
    # 2. Never disable/uninstall FLAG_PERSISTENT system packages
    # 3. Only use 'pm uninstall --user 0' on /data/app packages; use 'pm disable-user --user 0' on system packages
    local pkg_dump
    pkg_dump="$(adb_tv shell dumpsys package "${pkg}" 2>/dev/null | tr -d '\r' || true)"

    if echo "${pkg_dump}" | grep -qE "userId=1000([^0-9]|$)|sharedUser=.*android\.uid\.system"; then
        log_warn "[SAFEGUARD] Refusing to disable UID 1000 (android.uid.system) package: ${pkg}"
        return 0
    fi

    if echo "${pkg_dump}" | grep -E "pkgFlags=\[" | grep -qw "PERSISTENT"; then
        log_warn "[SAFEGUARD] Refusing to disable persistent system service package: ${pkg}"
        return 0
    fi

    local is_data_app="false"
    if echo "${pkg_dump}" | grep -qE "codePath=/data/app"; then
        is_data_app="true"
    fi

    if [[ "${dry_run}" == "true" ]]; then
        if [[ "${is_data_app}" == "true" ]]; then
            echo -e "  ${YELLOW}[DRY-RUN]${NC} Would uninstall removable /data/app bloatware (--user 0): ${pkg}"
        else
            echo -e "  ${YELLOW}[DRY-RUN]${NC} Would disable system bloatware (pm disable-user --user 0 ONLY): ${pkg}"
        fi
        return 0
    fi

    adb_tv shell am force-stop "${pkg}" >/dev/null 2>&1 || true
    adb_tv shell cmd appops set "${pkg}" RUN_IN_BACKGROUND ignore >/dev/null 2>&1 || true
    adb_tv shell cmd appops set "${pkg}" RUN_ANY_IN_BACKGROUND ignore >/dev/null 2>&1 || true

    local out_action
    if [[ "${is_data_app}" == "true" ]]; then
        out_action="$(adb_tv shell pm uninstall --user 0 "${pkg}" 2>&1 | tr -d '\r' || true)"
        if [[ "${out_action}" != *"Success"* ]]; then
            out_action="$(adb_tv shell pm disable-user --user 0 "${pkg}" 2>&1 | tr -d '\r' || true)"
        fi
    else
        # System package: ONLY use pm disable-user --user 0 (NEVER pm uninstall -k --user 0)
        out_action="$(adb_tv shell pm disable-user --user 0 "${pkg}" 2>&1 | tr -d '\r' || true)"
    fi

    if [[ -d "${BACKUP_ROOT}/latest" ]]; then
        echo "${pkg}" >> "${BACKUP_ROOT}/latest/removed_packages.log"
    fi
    log_ok "Disabled bloatware: ${BOLD}${pkg}${NC} (${out_action})"
}

# 5. Debloat Sony & Google/Telemetry Bloatware
cmd_debloat() {
    local dry_run="false"
    if [[ "${1:-}" == "--dry-run" ]]; then
        dry_run="true"
    fi

    ensure_adb
    log_step "Debloating ${TV_NAME} (Dry-Run: ${dry_run})"

    local enabled_pkgs pkg
    enabled_pkgs="$(adb_tv shell pm list packages -e | sed 's/^package://;s/\r$//')"

    log_info "Processing Sony retail demos, promos, and bloatware..."
    while IFS= read -r pkg; do
        [[ -z "${pkg}" ]] && continue
        disable_or_uninstall_pkg "${pkg}" "${dry_run}"
    done < <(expand_target_packages "${enabled_pkgs}" "${SONY_BLOAT_PACKAGES[@]}" | sort -u)

    log_info "Processing Samba TV spyware, Google Assistant daemon, and telemetry..."
    while IFS= read -r pkg; do
        [[ -z "${pkg}" ]] && continue
        disable_or_uninstall_pkg "${pkg}" "${dry_run}"
    done < <(expand_target_packages "${enabled_pkgs}" "${TELEMETRY_AND_GOOGLE_BLOAT[@]}" | sort -u)

    # Only disable stock launcher during debloat if Projectivy is already installed
    if echo "${enabled_pkgs}" | grep -qx "com.spocky.projengmenu"; then
        log_info "Projectivy Launcher detected — ensuring stock launchers & ad recommendations are disabled..."
        while IFS= read -r pkg; do
            [[ -z "${pkg}" ]] && continue
            disable_or_uninstall_pkg "${pkg}" "${dry_run}"
        done < <(expand_target_packages "${enabled_pkgs}" "${STOCK_LAUNCHER_PACKAGES[@]}" | sort -u)
    else
        log_warn "Projectivy Launcher not yet installed; keeping stock launcher enabled for safety."
        log_warn "Run './bravia-opt.sh install-launcher' to install Projectivy and disable stock launchers."
    fi

    log_ok "Debloat pass complete!"
}

# 6. Tune UI Animations, Input Latency, AOT Compilation, Caches, & Background Limits
cmd_tune() {
    ensure_adb
    log_step "Applying System Performance, Scrolling & Input Latency Tweaks"

    local enabled_pkgs
    enabled_pkgs="$(adb_tv shell pm list packages -e | sed 's/^package://;s/\r$//')"

    log_info "Disabling TalkBack screen-reader overhead while preserving Projectivy Launcher Home hook..."
    disable_or_uninstall_pkg "com.google.android.marvin.talkback" "false"
    if echo "${enabled_pkgs}" | grep -qx "com.spocky.projengmenu"; then
        adb_tv shell settings put secure enabled_accessibility_services "com.spocky.projengmenu/com.spocky.projengmenu.services.ProjectivyAccessibilityService" || true
        adb_tv shell settings put secure accessibility_enabled 1 || true
    fi

    log_info "Setting window, transition, and animator duration scales to ${ANIMATION_SCALE}x..."
    adb_tv shell settings put global window_animation_scale "${ANIMATION_SCALE}"
    adb_tv shell settings put global transition_animation_scale "${ANIMATION_SCALE}"
    adb_tv shell settings put global animator_duration_scale "${ANIMATION_SCALE}"

    log_info "Shortening remote hold-to-scroll delay (long_press_timeout -> ${LONG_PRESS_TIMEOUT}ms)..."
    adb_tv shell settings put secure long_press_timeout "${LONG_PRESS_TIMEOUT}"

    log_info "Capping background cached processes to ${MAX_CACHED_PROCESSES} to prevent ZRAM swap thrashing..."
    adb_tv shell settings put global activity_manager_constants "max_cached_processes=${MAX_CACHED_PROCESSES}" || true
    adb_tv shell device_config put activity_manager max_cached_processes "${MAX_CACHED_PROCESSES}" >/dev/null 2>&1 || true

    log_info "Restricting background execution (appops RUN_IN_BACKGROUND) on stock fallback & streaming apps..."
    local bg_restrict_pkgs=(
